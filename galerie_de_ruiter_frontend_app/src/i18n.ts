/** Applies the label maps above; a language that misses a key still reads in English. */
function translationFor(language: string, keys: Record<string, string>): Record<string, string> {
  const translation = { ...keys };
  for (const labels of [engagementLabels, chatAccessLabels, availabilityLabels, imageUploadLabels,
    aboutEditorLabels, cataloguePagingLabels, pageMetaLabels, routeLabels, footerLabels]) {
    Object.assign(translation, labels[language] ?? labels.en);
  }
  return translation;
}

/**
 * Belgian Dutch is the gallery's own language and English is its fallback, so those two travel
 * with the first paint. French, Dutch (NL) and German live in `i18nExtra` and are fetched when a
 * visitor picks one: the language table is the largest module in the app, and most visitors ever
 * read one language.
 */
const resources = {
  en: { translation: translationFor("en", enTranslation) },
  "nl-BE": { translation: translationFor("nl-BE", nlBeTranslation) },
};

void i18n
  .use(initReactI18next)
  .init({
    resources,
    // The gallery is Belgian: first-time visitors start in Belgian Dutch and can switch
    // from the language picker. A stored choice is honoured.
    lng: localStorage.getItem("galerie-language") || "nl-BE",
    fallbackLng: "en",
    interpolation: { escapeValue: false },
  });

/**
 * Brings in a language that did not ship with the first paint. Safe for any language: one that
 * is already loaded returns immediately.
 */
export async function ensureLanguage(language: string): Promise<void> {
  if (i18n.hasResourceBundle(language, "translation")) return;
  const { default: extraLanguages } = await import("./i18nExtra");
  const keys = extraLanguages[language]?.translation;
  if (keys) i18n.addResourceBundle(language, "translation", translationFor(language, keys), true, true);
}

export function formatEuroAmount(amount: number, locale: string): string {
  return new Intl.NumberFormat(locale, {
    style: "currency",
    currency: "EUR",
  }).format(amount);
}

