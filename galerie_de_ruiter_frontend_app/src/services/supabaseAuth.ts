import type { Registration } from "@/types/types";

/**
 * Where the project lives and the key the browser may hold. A function replaces it rather than the
 * constants being read directly, so a test can point the client at a project - and so a runtime
 * configuration would have somewhere to land later.
 */
let config = {
  url: (import.meta.env.VITE_SUPABASE_URL ?? "").trim().replace(/\/$/, ""),
  key: import.meta.env.VITE_SUPABASE_ANON_KEY ?? "",
};

/** Points the client at a project. The app never calls this; the tests do. */
export const configureSupabase = (next: { url: string; key: string }): void => {
  config = { url: next.url.trim().replace(/\/$/, ""), key: next.key };
};
/**
 * Signing in and signing up, against Supabase Auth rather than Keycloak.
 *
 * One account predates collecting addresses: `de-ruiter` was filed under
 * `de-ruiter@galerie-de-ruiter.be`, so the sign-in form still accepts the bare username and
 * `toEmail` completes it. Nothing new is created that way. Registration takes the address its owner
 * actually reads, because confirming an account and resetting a password both send mail - an
 * address nobody can receive at is a support ticket waiting to happen.
 *
 * Nothing here is a secret. The anonymous key is published to the browser by design and only ever
 * exchanges credentials for a token; the API verifies what comes back with Supabase's public keys.
 */

/** The domain the gallery's legacy account lives under, so its bare username still signs in. */
export const GALLERY_EMAIL_DOMAIN = "galerie-de-ruiter.be";

/** Whether a Supabase project is configured at all; without one, the pages say so instead of failing. */
export const isSupabaseConfigured = (): boolean => config.url.length > 0 && config.key.length > 0;

/** A signed-in session, in the shape the rest of the app already understands. */
export type SupabaseSession = {
  accessToken: string;
  refreshToken: string;
  /** Epoch milliseconds, so it can be compared with Date.now() without a library. */
  expiresAt: number;
  userId: string;
  email?: string;
};

/** What Supabase answered, before it is interpreted. */
type TokenResponse = {
  access_token?: string;
  refresh_token?: string;
  expires_in?: number;
  user?: { id?: string; email?: string };
  error?: string;
  error_code?: string;
  message?: string;
  msg?: string;
};

const toSession = (body: TokenResponse): SupabaseSession => {
  if (!body.access_token || !body.refresh_token || !body.user?.id) {
    throw new Error(body.error_code ?? body.error ?? body.message ?? body.msg ?? "signInFailed");
  }
  return {
    accessToken: body.access_token,
    refreshToken: body.refresh_token,
    expiresAt: Date.now() + (body.expires_in ?? 3600) * 1000,
    userId: body.user.id,
    email: body.user.email,
  };
};

/**
 * The address a typed username or address maps to when signing in.
 *
 * A bare username is understood only for the account that was created that way. Sign-up does not
 * come through here: `signUp` insists on an address that can receive mail.
 */
export const toEmail = (usernameOrEmail: string): string => {
  const value = usernameOrEmail.trim();
  if (!value) return "";
  if (value.includes("@")) return value.toLowerCase();
  return `${value.toLowerCase()}@${GALLERY_EMAIL_DOMAIN}`;
};

/** Whether the value is an address, rather than a username waiting to be filed under the gallery. */
export const isEmailAddress = (value: string): boolean =>
  /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value.trim());

/**
 * Whether the address belongs to the gallery's own domain.
 *
 * That domain is where the one legacy account lives, not a mailbox: nothing there receives mail,
 * and Supabase refuses the address as invalid. A new account must never be filed under it - whether
 * the address was typed in or generated by a client built before the form asked for a real one.
 */
export const isGalleryAddress = (value: string): boolean =>
  value.trim().toLowerCase().endsWith(`@${GALLERY_EMAIL_DOMAIN}`);

async function post(path: string, body: unknown, accessToken?: string): Promise<TokenResponse> {
  if (!isSupabaseConfigured()) {
    // Nothing to call: the build had no project URL. Saying so beats a network error that looks
    // like a wrong password.
    throw new Error("authNotConfigured");
  }
  const response = await fetch(`${config.url}${path}`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      apikey: config.key,
      ...(accessToken ? { Authorization: `Bearer ${accessToken}` } : {}),
    },
    body: JSON.stringify(body),
  });
  const json = (await response.json().catch(() => ({}))) as TokenResponse;
  if (!response.ok) {
    // The code is thrown, and every caller shows it: the sign-in form prints it beside the
    // translated sentence, and the registration form maps the codes a visitor can act on. Nothing
    // is written to the console - see src/noConsole.test.ts.
    throw new Error(json.error_code ?? json.error ?? json.message ?? json.msg ?? `http${response.status}`);
  }
  return json;
}

/** Exchanges a username or address, with its password, for a session. Throws an Error whose message is a translation key. */
export async function signIn(usernameOrEmail: string, password: string): Promise<SupabaseSession> {
  const body = await post("/auth/v1/token?grant_type=password", {
    email: toEmail(usernameOrEmail),
    password,
  });
  return toSession(body);
}

/**
 * Registers an account under an address its owner can receive mail at, and returns its session
 * when the project signs the visitor in straight away.
 *
 * The address is sent untouched - never completed with the gallery's domain - because a password
 * reset has to reach a real inbox. The display name travels as user metadata, which is what the
 * account menu and the profile read back. When confirmation is required the response carries no
 * session, and the caller shows the "check your inbox" message instead.
 *
 * Throws an Error whose message is a code: our own ("email_address_invalid",
 * "display_name_required") or Supabase's refusal.
 */
export async function signUp({ email, password, displayName }: Registration): Promise<SupabaseSession | null> {
  const address = email.trim().toLowerCase();
  if (!isEmailAddress(address)) throw new Error("email_address_invalid");
  if (isGalleryAddress(address)) throw new Error("gallery_email_not_accepted");
  const name = displayName.trim();
  if (!name) throw new Error("display_name_required");
  const body = await post("/auth/v1/signup", {
    email: address,
    password,
    data: { username: name, full_name: name },
  });
  return body.access_token ? toSession(body) : null;
}

/** A fresh access token, from the refresh token a session already holds. */
export async function refresh(session: SupabaseSession): Promise<SupabaseSession> {
  const body = await post("/auth/v1/token?grant_type=refresh_token", {
    refresh_token: session.refreshToken,
  });
  return toSession(body);
}

/** Ends the session server-side. Failure is not worth surfacing: the local session goes either way. */
export async function signOut(session: SupabaseSession): Promise<void> {
  try {
    await post("/auth/v1/logout", {}, session.accessToken);
  } catch {
    // A revoked or expired token is already signed out; the caller clears its own state regardless.
  }
}

/**
 * Sets a new password for the signed-in account.
 *
 * The identity provider owns this, not the gallery: it holds the password and knows how to store it,
 * and the profile row never sees one. The access token is the proof that the person asking is the
 * account being changed, which is why the current password is not needed here - but the form asks
 * for it anyway, because someone who left a browser signed in should not be able to lock its owner
 * out.
 *
 * Throws an Error whose message is a code ("weak_password", "same_password", "http401").
 */
export async function updatePassword(session: SupabaseSession, password: string): Promise<void> {
  if (!isSupabaseConfigured()) throw new Error("authNotConfigured");
  const response = await fetch(`${config.url}/auth/v1/user`, {
    method: "PUT",
    headers: {
      "Content-Type": "application/json",
      apikey: config.key,
      Authorization: `Bearer ${session.accessToken}`,
    },
    body: JSON.stringify({ password }),
  });
  if (response.ok) return;
  const json = (await response.json().catch(() => ({}))) as TokenResponse;
  // The form shows this code; the console stays clean (src/noConsole.test.ts).
  throw new Error(json.error_code ?? json.error ?? json.msg ?? json.message ?? `http${response.status}`);
}

/**
 * Changes a password after proving the current one belongs to the account.
 *
 * The endpoint that sets a password trusts the access token, so the token alone would let anyone
 * at an unlocked browser lock its owner out. Supabase's password grant is the check it offers:
 * asking for a token with the current password must succeed before anything is written. The fresh
 * session is returned so the caller can adopt the tokens the change was made with.
 *
 * The address is the one the identity provider holds (the caller reads it from the token), never
 * the editable profile field: that field may name a different address, which would make a correct
 * password look wrong.
 *
 * Throws an Error whose message is a code ("invalid_credentials", "weak_password", ...).
 */
export async function changePassword(email: string, currentPassword: string, newPassword: string): Promise<SupabaseSession> {
  const verified = await signIn(email, currentPassword);
  await updatePassword(verified, newPassword);
  return verified;
}
